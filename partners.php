  <script>
    document.getElementById('partnerForm')?.addEventListener('submit', async function(e) {
      e.preventDefault();
      const form = this;
      const btn = document.getElementById('partnerSubmitBtn');
      const alertBox = document.getElementById('partnerFormAlert');

      btn.disabled = true;
      btn.innerHTML = '<i class="fas fa-spinner fa-spin"></i> Saving Application...';

      const formData = new FormData(form);
      const data = Object.fromEntries(formData.entries());

      try {
        const response = await fetch('api/submit_partner.php', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify(data)
        });
        const res = await response.json();

        alertBox.style.display = 'block';
        if (res.success) {
          alertBox.style.background = '#dcfce7';
          alertBox.style.color = '#15803d';
          alertBox.style.border = '1px solid #86efac';
          alertBox.innerHTML = `<i class="fas fa-check-circle"></i> <strong>Success!</strong> ${res.message}`;
          form.reset();
        } else {
          alertBox.style.background = '#fee2e2';
          alertBox.style.color = '#b91c1c';
          alertBox.style.border = '1px solid #fca5a5';
          alertBox.innerHTML = `<i class="fas fa-exclamation-triangle"></i> <strong>Error:</strong> ${res.message}`;
        }
      } catch (err) {
        alertBox.style.display = 'block';
        alertBox.style.background = '#fee2e2';
        alertBox.style.color = '#b91c1c';
        alertBox.style.border = '1px solid #fca5a5';
        alertBox.innerHTML = `<i class="fas fa-exclamation-triangle"></i> Network error. Please try again.`;
      } finally {
        btn.disabled = false;
        btn.innerHTML = 'Submit Partnership Application <i class="fas fa-paper-plane"></i>';
      }
    });
  </script>
